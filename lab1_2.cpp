#include <stdio.h>
#include <stdlib.h>

int main()
{
    // Варіант 2 (для варіанта 17 у списку групи: 17 % 5 = 2)
    int a1 = 2, a2 = 3, b1, b2, b3;

    // 1. a2 *= 10: скорочена операція множення.
    // Значення a2 стає 3 * 10 = 30
    a2 *= 10;

    // 2. b1 = a1^3 + a2 (запис a13 означає a1 у кубі):
    // 2 * 2 * 2 + 30 = 8 + 30 = 38
    b1 = a1 * a1 * a1 + a2;

    // 3. b2 = a1 > a2: операція порівняння.
    // 2 > 30 є хибним, тому логічний результат дорівнює 0
    b2 = a1 > a2;

    // 4. b3 = ++b2: префіксний інкремент.
    // Спочатку b2 збільшується на 1 (стає 1), а потім це значення присвоюється b3 (b3 = 1)
    b3 = ++b2;

    printf("a1=%d a2=%d b1=%d b2=%d b3=%d\n", a1, a2, b1, b2, b3);

    float f1 = 1.5f, f2 = 1.5f, r1, r2;

    // 5. r1 = 2 * f1 - f2:
    // 2 * 1.5 - 1.5 = 3.0 - 1.5 = 1.5
    r1 = 2.0f * f1 - f2;

    // 6. r2 = (f1 == f2) ? f1 * 3 : f2 * 5: тернарний оператор.
    // Умова 1.5 == 1.5 є істинною, тому обчислюється перший вираз: 1.5 * 3 = 4.5
    r2 = (f1 == f2) ? f1 * 3.0f : f2 * 5.0f;

    printf("r1=%5.2f r2=%5.2f\n", r1, r2);

    system("pause");
    return 0;
}
